-- ===== supabase/migrations/0001_init.sql =====
-- GoodPush — initial schema
-- Run in Supabase: SQL Editor → New query → paste → Run

create table if not exists public.subscribers (
  id            text primary key,                 -- device id generated by the app
  name          text,
  categories    text[] not null default '{}',
  hour          smallint not null default 8 check (hour between 0 and 23),
  time_zone     text not null default 'UTC',
  lang          text not null default 'en' check (lang in ('en','es','fr')),
  source        text,                             -- first-touch: which video / channel brought them
  endpoint      text not null,
  p256dh        text not null,
  auth          text not null,
  active        boolean not null default true,
  premium       boolean not null default false,
  last_sent_on  date,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists subscribers_active_idx on public.subscribers (active);
create index if not exists subscribers_source_idx on public.subscribers (source);

-- Lock the table: only the server (service role key) can read/write.
alter table public.subscribers enable row level security;
-- (No policies on purpose → anon/public keys get nothing.)

-- Handy view for your growth dashboard (Table editor → stats)
create or replace view public.stats as
select
  count(*) filter (where active)                                   as active_subscribers,
  count(*) filter (where created_at > now() - interval '1 day')    as new_today,
  count(*) filter (where created_at > now() - interval '7 days')   as new_7d,
  count(*) filter (where premium)                                  as premium
from public.subscribers;

create or replace view public.stats_by_source as
select coalesce(source, 'direct') as source, count(*) as subscribers
from public.subscribers where active
group by 1 order by 2 desc;

revoke all on public.stats, public.stats_by_source from anon, authenticated;

-- ===== supabase/migrations/0002_premium.sql =====
-- GoodPush — Premium (Stripe) + extra daily pushes
-- Run after 0001_init.sql

-- Premium lives in its own table: someone can pay before turning on notifications.
create table if not exists public.premium (
  device_id               text primary key,
  stripe_customer_id      text,
  stripe_subscription_id  text unique,
  status                  text not null default 'incomplete',  -- active | trialing | past_due | canceled | ...
  current_period_end      timestamptz,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);
alter table public.premium enable row level security;  -- server only

-- Extra local hours for Premium pushes (max 2) and which slots were sent today
alter table public.subscribers add column if not exists extra_hours smallint[] not null default '{}';
alter table public.subscribers add column if not exists sent_slots smallint[] not null default '{}';

-- Helper: is a device premium right now?
create or replace view public.premium_active as
select device_id from public.premium where status in ('active', 'trialing');
revoke all on public.premium_active from anon, authenticated;

-- Stats now include premium + MRR estimate (2.99 €)
create or replace view public.stats as
select
  (select count(*) from public.subscribers where active)                                  as active_subscribers,
  (select count(*) from public.subscribers where created_at > now() - interval '1 day')   as new_today,
  (select count(*) from public.subscribers where created_at > now() - interval '7 days')  as new_7d,
  (select count(*) from public.premium_active)                                            as premium,
  round((select count(*) from public.premium_active) * 2.99, 2)                           as mrr_eur;
revoke all on public.stats from anon, authenticated;

-- ===== supabase/migrations/0003_accounts.sql =====
-- GoodPush — optional accounts (Google, Apple, email code)
-- Run after 0002_premium.sql. Then enable providers in Supabase → Authentication → Providers.

-- Devices and Premium can belong to an account
alter table public.subscribers add column if not exists user_id uuid references auth.users(id) on delete set null;
create index if not exists subscribers_user_idx on public.subscribers (user_id);

alter table public.premium add column if not exists user_id uuid references auth.users(id) on delete set null;
create index if not exists premium_user_idx on public.premium (user_id);

-- Synced app data (favorites, history, streak, settings) + marketing consent
create table if not exists public.profiles (
  user_id               uuid primary key references auth.users(id) on delete cascade,
  email                 text,
  lang                  text not null default 'en',
  data                  jsonb not null default '{}'::jsonb,
  marketing_opt_in      boolean not null default false,
  marketing_consent_at  timestamptz,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);
alter table public.profiles enable row level security;  -- server only (service role)

-- Premium is active for a device OR for every device of the paying account
create or replace view public.premium_active as
select device_id, user_id from public.premium where status in ('active', 'trialing');
revoke all on public.premium_active from anon, authenticated;

-- Email marketing audience (only people who explicitly opted in) — export to Brevo / Resend / MailerLite
create or replace view public.marketing_audience as
select email, lang, data -> 'profile' -> 'categories' as categories, marketing_consent_at
from public.profiles
where marketing_opt_in and email is not null;
revoke all on public.marketing_audience from anon, authenticated;

-- ===== supabase/migrations/0004_feedback_pause_email.sql =====
-- GoodPush — feedback, notification pause / weekdays, email marketing sync
-- Run after 0003_accounts.sql

-- In-app feedback (also sent to Sentry User Feedback)
create table if not exists public.feedback (
  id          bigint generated always as identity primary key,
  created_at  timestamptz not null default now(),
  device_id   text,
  user_id     uuid references auth.users(id) on delete set null,
  rating      smallint check (rating between 1 and 5),
  kind        text check (kind in ('idea', 'problem', 'love', 'other')),
  message     text not null check (char_length(message) between 1 and 2000),
  email       text,
  lang        text,
  page        text,
  premium     boolean not null default false
);
alter table public.feedback enable row level security;  -- server only
create index if not exists feedback_created_idx on public.feedback (created_at desc);

-- Notification control: pause until a date, and which local weekdays (0 = Sunday … 6 = Saturday)
alter table public.subscribers add column if not exists paused_until timestamptz;
alter table public.subscribers add column if not exists days smallint[] not null default '{0,1,2,3,4,5,6}';

-- Email marketing: remember what was synced to Brevo
alter table public.profiles add column if not exists brevo_synced_at timestamptz;

-- Quick dashboards
create or replace view public.feedback_summary as
select date_trunc('week', created_at) as week, kind, count(*) as n, round(avg(rating), 2) as avg_rating
from public.feedback group by 1, 2 order by 1 desc, 2;
revoke all on public.feedback_summary from anon, authenticated;

-- ===== supabase/migrations/0005_topics_quotes.sql =====
-- GoodPush — sub-topics (football, tennis, exams…) + "in the news" quotes
-- Run after 0004_feedback_pause_email.sql

alter table public.subscribers add column if not exists topics text[] not null default '{}';
create index if not exists subscribers_topics_idx on public.subscribers using gin (topics);

-- Real quotes from the news. Add rows in Table editor, always with the source link,
-- then tick `approved`. On `publish_on`, everyone who picked `topic` gets it.
create table if not exists public.quotes (
  id           bigint generated always as identity primary key,
  topic        text not null,                       -- e.g. football, tennis, startup (see src/lib/data/topics.ts)
  author       text not null,                       -- e.g. Kylian Mbappé
  quote_en     text,
  quote_es     text,
  quote_fr     text,                                -- fill at least one; empty languages show the original
  context      text,                                -- e.g. "after the Clásico" (for you, not shown)
  source_url   text not null check (source_url ~ '^https?://'),
  said_on      date,
  publish_on   date not null default current_date,
  approved     boolean not null default false,
  created_at   timestamptz not null default now(),
  constraint quotes_has_text check (coalesce(quote_en, quote_es, quote_fr) is not null)
);
alter table public.quotes enable row level security;  -- server only
create index if not exists quotes_publish_idx on public.quotes (publish_on) where approved;

-- Who picked what (for deciding which quotes to look for)
create or replace view public.topics_popularity as
select t as topic, count(*) as subscribers
from public.subscribers, unnest(topics) t
where active
group by 1 order by 2 desc;
revoke all on public.topics_popularity from anon, authenticated;

-- ===== supabase/migrations/0006_movies.sql =====
-- GoodPush — movie mode inside every theme (topics like 'sport_movies', 'calm_movies'…)
